import re
import sys
from pathlib import Path

from descriptor_bytes import normalize_descriptor


def split_unmarshal(block):
    if len(block.splitlines()) < 360:
        return [block]
    match = re.match(r'func \(m \*(\w+)\) Unmarshal\(dAtA \[\]byte\) error \{', block)
    if match is None:
        raise ValueError('oversize declaration cannot be split')
    message = match.group(1)
    cases = list(re.finditer(r'^\t\tcase (\d+):\n', block, re.M))
    default = block.index('\t\tdefault:', cases[-1].end())
    rewritten = block[:cases[0].start()]
    helpers = []
    for index, case in enumerate(cases):
        end = cases[index + 1].start() if index + 1 < len(cases) else default
        body = block[case.end():end].rstrip()
        body = re.sub(r'^\t\t', '', body, flags=re.M)
        body = re.sub(r'^(\s*)return (.+)$', r'\1return iNdEx, \2', body, flags=re.M)
        number = case.group(1)
        name = f'unmarshalField{number}'
        helpers.append(f'func (m *{message}) {name}(dAtA []byte, iNdEx, wireType int) (int, error) {{\n\tl := len(dAtA)\n{body}\n\treturn iNdEx, nil\n}}\n\n')
        rewritten += f'\t\tcase {number}:\n\t\t\tvar err error\n\t\t\tiNdEx, err = m.{name}(dAtA, iNdEx, wireType)\n\t\t\tif err != nil {{\n\t\t\t\treturn err\n\t\t\t}}\n'
    rewritten += block[default:]
    return [rewritten] + helpers


def generated_files(source, package):
    if len(source) > 2097152:
        raise ValueError('generated source byte limit')
    source = normalize_descriptor(source)
    imports = re.search(r'import \((.*?)\n\)', source, re.S).group(1)
    entries = re.findall(r'^\s*(\w+)\s+"([^"]+)"', imports, re.M)
    starts = [match.start() for match in re.finditer(r'^(?:func|type|var|const) ', source, re.M)]
    blocks = []
    for start, end in zip(starts, starts[1:] + [len(source)]):
        blocks.extend(split_unmarshal(source[start:end]))
    groups = []
    current = ''
    for block in blocks:
        if current.count('\n') + block.count('\n') > 340 and current:
            groups.append(current)
            current = ''
        current += block
    if current:
        groups.append(current)
    result = {}
    for index, body in enumerate(groups):
        selected = [(alias, name) for alias, name in entries if re.search(r'\b' + re.escape(alias) + r'\.', body) or alias == '_' and index == 0]
        selected.sort(key=lambda entry: entry[1])
        header = '// Code generated by protoc-gen-gogo and split_proto.py. DO NOT EDIT.\npackage ' + package + '\n\n'
        if len(selected) == 1:
            alias, name = selected[0]
            header += f'import {alias} "{name}"\n\n'
        elif selected:
            header += 'import (\n' + ''.join(f'\t{alias} "{name}"\n' for alias, name in selected) + ')\n\n'
        content = header + body.rstrip() + '\n'
        if len(content.splitlines()) >= 400:
            raise ValueError('split generated source reaches line cap')
        result[f'generated_{index:03}.pb.go'] = content
    return result


def main():
    mode, source_directory, repository = sys.argv[1:]
    for package in ['validatorset']:
        source = Path(source_directory) / 'traderswift' / package / 'v1' / f'{package}.pb.go'
        expected = generated_files(source.read_text(), package)
        directory = Path(repository) / package
        present = {path.name for path in directory.glob('*.pb.go')}
        if mode == 'write':
            for name in present - expected.keys():
                (directory / name).unlink()
            for name, content in expected.items():
                (directory / name).write_text(content)
        elif mode == 'check':
            if present != expected.keys():
                raise ValueError(f'{package}: generated binding file set differs')
            for name, content in expected.items():
                if (directory / name).read_text() != content:
                    raise ValueError(f'{package}/{name}: generated binding drift')
        else:
            raise ValueError('expected write or check')
    print('PASS generated binding ' + mode)


if __name__ == '__main__':
    main()
